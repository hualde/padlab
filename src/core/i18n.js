let currentLocale = 'es';

export const LOCALES = [
  { id: 'es', labelKey: 'language.es' },
  { id: 'en', labelKey: 'language.en' },
  { id: 'fr', labelKey: 'language.fr' },
];

export function setLocale(locale) {
  currentLocale = MESSAGES[locale] ? locale : 'es';
  if (typeof document !== 'undefined') {
    document.documentElement.lang = currentLocale;
  }
  return currentLocale;
}

export function getLocale() {
  return currentLocale;
}

export function localeTag() {
  return { es: 'es-ES', en: 'en-GB', fr: 'fr-FR' }[currentLocale] || 'es-ES';
}

export function t(key, vars = {}) {
  const dictionary = MESSAGES[currentLocale] || MESSAGES.es;
  const fallback = MESSAGES.es;
  const template = dictionary[key] ?? fallback[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name) => (
    vars[name] == null ? match : String(vars[name])
  ));
}

export function tn(key, count, vars = {}) {
  const one = new Intl.PluralRules(localeTag()).select(count) === 'one';
  return t(`${key}.${one ? 'one' : 'many'}`, { count, ...vars });
}

export function translationKeys(locale = currentLocale) {
  return Object.keys(MESSAGES[locale] || {});
}

export function applyTranslations(root = document) {
  for (const element of root.querySelectorAll('[data-i18n]')) {
    element.textContent = t(element.dataset.i18n);
  }
  for (const element of root.querySelectorAll('[data-i18n-title]')) {
    element.setAttribute('title', t(element.dataset.i18nTitle));
  }
  for (const element of root.querySelectorAll('[data-i18n-aria-label]')) {
    element.setAttribute('aria-label', t(element.dataset.i18nAriaLabel));
  }
  for (const element of root.querySelectorAll('[data-i18n-placeholder]')) {
    element.setAttribute('placeholder', t(element.dataset.i18nPlaceholder));
  }
}
